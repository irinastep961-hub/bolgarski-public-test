const SUBJ = ['Аз', 'Ти', 'Той / Тя / То', 'Ние', 'Вие', 'Те'];

function table(verb: string): { head: string[]; rows: string[][] } {
  return { head: ['Лицо', 'Форма', 'Перевод'], rows: PARADIGMS[verb].map((f, i) => [SUBJ[i], f, RU[verb][i]]) };
}

/** Ловушки: полные неверные формы и «хвосты»-окончания, с объяснением, для какого лица они подходят */
function formTraps(verb: string, rightIdx: number, stem: string): Trap[] {
  const forms = PARADIGMS[verb];
  const out: Trap[] = [];
  forms.forEach((f, i) => {
    if (i === rightIdx) return;
    const say = `«${f}» — форма для «${PERSON[i]}». После «${PERSON[rightIdx]}» нужна форма «${forms[rightIdx]}».`;
    out.push({ has: f, say });
    const ending = f.slice(stem.length);
    if (ending && ending !== forms[rightIdx].slice(stem.length)) out.push({ has: ending, say: `Окончание «-${ending}» — для «${PERSON[i]}». После «${PERSON[rightIdx]}» нужно «-${forms[rightIdx].slice(stem.length)}»: ${forms[rightIdx]}.` });
  });
  return out;
}

function fc(prompt: string, verb: string, rightIdx: number, wrongIdx: [number, number], note: string): FormChoiceSource {
  const forms = PARADIGMS[verb];
  const subj = PERSON[rightIdx];
  return {
    prompt,
    answer: forms[rightIdx],
    wrong: wrongIdx.map((i) => ({ form: forms[i], why: `«${forms[i]}» — форма для «${PERSON[i]}». Здесь подлежащее «${subj}», нужна форма «${forms[rightIdx]}».` })),
    note,
  };
}

