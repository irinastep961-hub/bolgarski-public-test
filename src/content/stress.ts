export const ACUTE = '\u0301';

/** Слово или фраза без знаков ударения -> с ударением (знак U+0301 после ударной гласной) */
export const STRESS: Record<string, string> = Object.fromEntries(
  RAW.map((r) => [r.replace(/\|/g, ''), r.replace(/\|/g, ACUTE)]),
);

export function stressed(bg: string): string | undefined {
  return STRESS[bg.trim().toLowerCase()];
}

