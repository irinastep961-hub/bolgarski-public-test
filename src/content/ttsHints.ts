// Подсказки ударения для синтезатора речи (по умолчанию ОТКЛЮЧЕНЫ — см. voicePrefs.ts).
// Проверка на устройстве пользователя показала: голос Windows знак U+0301 не понимает, часть слов звучит хуже,
// поэтому в обычной работе в голос уходит слово без знака. Код оставлен для сравнения «без подсказки / с подсказкой».
//
// ПРИЧИНА ОШИБОК. Таблица STRESS (stress.ts) нужна только для показа: до синтезатора она не доходила,
// слово уходило в голос «как есть», а ударение голос выбирал сам. В словах уроков 1–10 его догадка
// чаще совпадала с верным ударением; в части слов уроков 11–14 и в слове «благодаря» — нет.
// Поэтому для слов из списка ниже в голос передаётся текст со знаком ударения U+0301 после ударной гласной.
// На экране пользователь по-прежнему видит обычное написание: подсказка добавляется только в момент озвучивания.
//
// ЧЕСТНОЕ ОГРАНИЧЕНИЕ. Учитывает ли знак ударения конкретный голос (Microsoft, Google, Apple), из приложения
// узнать нельзя — это проверяется только на слух на устройстве (страница «Озвучивание» → «Проверка ударений»).
// Если голос ведёт себя хуже, подсказку можно отключить там же.
import { ACUTE, STRESS } from './stress';

/** Слова и словосочетания, для которых голосу отправляется знак ударения. Формы слов точные (без падежей и артиклей). */
export const SPEECH_HINT_WORDS: readonly string[] = [
  'благодаря',
  // урок 11
  'подстригване', 'боядисване', 'прическа', 'коса', 'по-късо', 'свободен',
  // урок 12
  'обувки', 'да върна',
  // урок 13
  'банкомат', 'пари', 'превод', 'да платя',
  // урок 14
  'интересно',
];

const LETTERS = 'а-яА-ЯѝЍ';

function escape(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Позиция (в символах слова без знаков) ударной гласной в записи STRESS: «пари́» -> 4 */
function markIndex(accented: string): number {
  return accented.indexOf(ACUTE);
}

const RULES = SPEECH_HINT_WORDS.map((key) => {
  const accented = STRESS[key];
  if (!accented) throw new Error(`Нет ударения в таблице для «${key}»`);
  return { key, at: markIndex(accented), re: new RegExp(`(?<![${LETTERS}])${escape(key)}(?![${LETTERS}])`, 'giu') };
});

/**
 * Возвращает текст для синтезатора: в словах из SPEECH_HINT_WORDS добавлен знак ударения.
 * Регистр букв сохраняется; остальной текст не меняется.
 */
export function applySpeechHints(text: string): string {
  let out = text;
  for (const r of RULES) {
    out = out.replace(r.re, (m) => m.slice(0, r.at) + ACUTE + m.slice(r.at));
  }
  return out;
}

/** Текст, который уходит в голос: с подсказками ударения или без них (по настройке пользователя). */
export function speechText(text: string, hintsOn: boolean): string {
  return hintsOn ? applySpeechHints(text) : text;
}
