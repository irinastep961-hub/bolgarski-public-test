// Урок 15. Глагол «съм» — быть: утверждения, отрицания и вопросы с «ли».
import type { LessonSource, Trap } from '../types';

const PERSON: Record<string, string> = { съм: 'аз', си: 'ти', е: 'той / тя / то', сме: 'ние', сте: 'вие', са: 'те' };

/** Ловушки для пропуска: любая неверная форма «съм» получает объяснение, для какого лица она нужна */
function formTraps(given: string, right: string): Trap[] {
  return Object.keys(PERSON)
    .filter((f) => f !== right)
    .map((f) => ({ has: f, say: `«${f}» — форма для «${PERSON[f]}». После «${given}» нужна форма «${right}».` }));
}

