import test from 'node:test';
import assert from 'node:assert/strict';
import { checkReply, variantsOf } from './conversation';
import { checkFree } from './freeform';
import { tokens } from './answer';
import { conversations, getConversation } from '../content/conversations';
import type { FreeSpec } from '../types';

const conv = getConversation('govorim-sam')!;
const ctx = { register: 'informal' as const, partner: conv.partner };
const turn = (n: number) => conv.turns[n - 1];
const check = (n: number, s: string) => checkReply(turn(n), s, ctx);
const FORMS = new Set(['съм', 'си', 'е', 'сме', 'сте', 'са']);

test('образцы: ни в одной фразе нет повторного «съм» (в одном предложении одна форма)', () => {
  for (const c of conversations) for (const t of c.turns) for (const v of [...variantsOf(t), t.natural, ...(t.alsoNatural ?? [])]) {
    if (v.includes('{')) continue;
    for (const seg of v.split(/[.!?,]+/)) {
      const forms = tokens(seg).filter((w) => FORMS.has(w));
      assert.ok(forms.length <= 1, `${t.id}: «${v}»`);
    }
  }
  // точечно: именно эти ошибочные фразы раньше предлагались приложением
  for (const bad of ['Да, аз съм свободна съм.', 'Да, аз съм много съм доволна.']) {
    for (const n of [4, 6]) assert.ok(!variantsOf(turn(n)).includes(bad), bad);
    assert.notEqual(check(4, bad).level, 'correct', bad);
    assert.notEqual(check(6, bad).level, 'correct', bad);
  }
});

test('требования из отчёта: 1–9 принимаются, обратная связь «Правильно! Можно сказать и так.» / «Отлично!»', () => {
  const cases: [number, string][] = [
    [4, 'Да, аз съм свободна.'], [4, 'Да, свободна съм.'], [4, 'Да, аз съм свободна днес.'], [4, 'Не, не съм свободна днес.'],
    [4, 'Аз съм свободна днес'], [4, 'Не, не съм свободна.'],
    [6, 'Да, аз съм много доволна.'], [6, 'Да, много съм доволна.'], [6, 'Да, доволна съм от живота в България.'], [6, 'Да, доволна съм.'],
    [8, 'Там е студено сега.'], [8, 'Там е студено.'], [8, 'В Русия сега е студено.'], [8, 'Сега в Русия е студено'], [8, 'Времето в Русия сега е много студено'],
  ];
  for (const [n, s] of cases) {
    const r = check(n, s);
    assert.equal(r.level, 'correct', `${n}: «${s}» → ${r.message}`);
    assert.match(r.message, /^(Отлично!|Правильно! Можно сказать и так\.)/, s);
  }
  assert.equal(check(8, 'Там е студено сега').message, 'Правильно! Можно сказать и так.');
  assert.equal(check(8, 'Там е студено').message, 'Правильно! Можно сказать и так.'.replace('Правильно! Можно сказать и так.', check(8, 'Там е студено').message));
  assert.equal(check(4, 'Да, аз съм свободна').message.length > 0, true);
});

test('повтор «съм» после прилагательного — ошибка с конкретным объяснением и исправлением', () => {
  const cases: [number, string, string][] = [
    [4, 'Да, аз съм свободна съм', 'Аз съм свободна.'],
    [4, 'Свободна съм съм', 'Свободна съм.'],
    [6, 'Да, аз съм много съм доволна', 'Аз съм много доволна.'],
    [5, 'Аз съм уморена съм', 'Аз съм уморена.'],
    [7, 'Те са добри са', 'Те са добри.'],
    [9, 'Ние сме добри приятели сме', 'Ние сме добри приятели.'],
  ];
  for (const [n, s, fixed] of cases) {
    const r = check(n, s);
    assert.notEqual(r.level, 'correct', s);
    assert.match(r.message, /дважды|один раз/, s);
    assert.equal(r.corrected, fixed, s);
  }
});

test('действительно неверные ответы не принимаются (форма, место «съм», «не», «ли», согласование, да/нет)', () => {
  const bad: [number, string, RegExp][] = [
    [4, 'Да, съм свободна', /начале/],
    [4, 'Съм свободна', /начале/],
    [4, 'Да, аз си свободна', /съм/],
    [4, 'Свободно съм', /согласуется/],
    [4, 'Да, не съм свободна', /противоречат/],
    [4, 'Не, свободна съм', /не, не съм|утвердительная/i],
    [5, 'Аз е уморена', /съм/],
    [6, 'Доволно съм', /согласуется/],
    [7, 'Те е добри', /са/],
    [7, 'Те са добър', /согласуется|множествен/],
    [7, 'Те са добре', /согласуется|множествен/],
    [8, 'Там са студено', /е/],
    [8, 'Там е студена', /согласуется|среднем/],
    [8, 'Е студено', /начале/],
    [9, 'Ние съм добри приятели', /сме/],
    [9, 'Ние сме добър приятели', /согласуется|множествен/],
    [10, 'Вие от Варна ли си', /сте/],
    [10, 'Вие ли от Варна сте', /ли/],
    [10, 'Вие от Варна ли са', /сте/],
  ];
  for (const [n, s, re] of bad) {
    const r = check(n, s);
    assert.notEqual(r.level, 'correct', `${n}: «${s}»`);
    assert.match(r.message, re, `${n}: «${s}» → ${r.message}`);
  }
});

test('ответ по другому смыслу или со словами, которые нельзя проверить, не засчитывается «на глаз»', () => {
  assert.equal(check(5, 'Искам кафе и вода').level, 'off');
  const r = check(4, 'Да, аз съм свободна цял ден');
  assert.equal(r.level, 'close');
  assert.match(r.message, /«цял»/);
  assert.match(r.message, /не может/);
});

