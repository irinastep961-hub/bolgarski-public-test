test('все лица: аз, ти, той/тя, ние, вие, те — ни одна форма не удваивается и не теряется', () => {
  const mk = (form: string, preds: string[], extra: Partial<FreeSpec> = {}): FreeSpec => ({ forms: [form], predicates: preds, stems: ['готов', 'доволн', 'уморен', 'умор', 'довол'], extras: ['много', 'ние', 'вие', 'те', 'ти', 'той', 'тя', 'то'], ...extra });
  const rows: [string, string, string[], string[], string[]][] = [
    ['съм', 'Аз съм свободна', ['свободна', 'свободен'], ['Аз съм много свободна', 'Свободна съм', 'Да, аз съм свободна'], ['Аз съм свободна съм', 'Съм свободна', 'Аз си свободна']],
    ['си', 'Ти си готов', ['готов', 'готова'], ['Ти си много готов', 'Готов си', 'Ти си готова'], ['Ти си готов си', 'Си готов', 'Ти съм готов']],
    ['е', 'Той е уморен', ['уморен', 'уморена', 'уморено'], ['Тя е уморена', 'То е уморено', 'Той е много уморен', 'Уморен е'], ['Тя е уморена е', 'Е уморена', 'Той са уморен']],
    ['сме', 'Ние сме готови', ['готови'], ['Ние сме много готови', 'Готови сме'], ['Ние сме готови сме', 'Сме готови', 'Ние съм готови']],
    ['сте', 'Вие сте готови', ['готови'], ['Вие сте много готови', 'Готови сте'], ['Вие сте готови сте', 'Сте готови', 'Вие си готови']],
    ['са', 'Те са доволни', ['доволни'], ['Те са доволни', 'Те са много доволни', 'Доволни са'], ['Те са доволни са', 'Са доволни', 'Те е доволни']],
  ];
  for (const [form, , preds, good, bad] of rows) {
    const spec = mk(form, preds);
    for (const g of good) assert.equal(checkFree(spec, g).status, 'ok', `${form}: «${g}»`);
    for (const b of bad) assert.equal(checkFree(spec, b).status, 'error', `${form}: «${b}»`);
  }
  // примеры из отчёта
  assert.equal(checkFree(mk('е', ['уморена']), 'Тя е уморена').status, 'ok');
  assert.equal(checkFree(mk('сме', ['готови']), 'Ние сме готови').status, 'ok');
  assert.equal(checkFree(mk('са', ['доволни']), 'Те са доволни').status, 'ok');
});

test('ответы «Да/Не» согласуются с отрицанием и в вопросах про любое лицо', () => {
  const spec: FreeSpec = { forms: ['съм'], predicates: ['готов', 'готова'], yesNo: true };
  assert.equal(checkFree(spec, 'Не, не съм готов').status, 'ok');
  assert.equal(checkFree(spec, 'Не съм готов').status, 'ok');
  assert.equal(checkFree(spec, 'Да, готов съм').status, 'ok');
  assert.equal(checkFree(spec, 'Да, не съм готов').status, 'error');
});

